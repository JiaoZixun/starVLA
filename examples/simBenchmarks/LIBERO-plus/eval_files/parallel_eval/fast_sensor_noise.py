"""Fast, protocol-compatible LIBERO-plus sensor-noise transforms.

LIBERO-plus applies ``glass_blur`` to every rendered observation for the
Sensor Noise tasks.  The upstream implementation performs the pixel-swap
loop in Python, which makes a failed episode spend several minutes in image
augmentation alone.  The implementation below keeps the same random-offset
sequence and swap order, but runs the loop through Numba when it is available.

The module is deliberately kept in the tracked evaluation code instead of
editing the vendored LIBERO-plus checkout under ``playground/``.
"""

from __future__ import annotations

import logging
from typing import Any

import numpy as np
from skimage.filters import gaussian

try:
    from numba import njit
except ImportError:  # pragma: no cover - exercised only in minimal eval envs
    njit = None


LOGGER = logging.getLogger(__name__)
NUMBA_AVAILABLE = njit is not None


if NUMBA_AVAILABLE:

    @njit(cache=True, nogil=True)
    def _apply_pixel_swaps(image: np.ndarray, offsets: np.ndarray, max_delta: int, iterations: int) -> None:
        """Apply the upstream glass-blur swaps in their original order."""

        height, width = image.shape[:2]
        swaps_per_iteration = (height - 2 * max_delta) * (width - 2 * max_delta)
        for iteration in range(iterations):
            offset_base = iteration * swaps_per_iteration
            offset_index = 0
            # Match env_wrapper.glass_blur exactly: both ranges descend and
            # the destination is (h + dy, w + dx).
            for h in range(height - max_delta, max_delta, -1):
                for w in range(width - max_delta, max_delta, -1):
                    dx = int(offsets[offset_base + offset_index, 0])
                    dy = int(offsets[offset_base + offset_index, 1])
                    h_prime = h + dy
                    w_prime = w + dx
                    for channel in range(image.shape[2]):
                        value = image[h, w, channel]
                        image[h, w, channel] = image[h_prime, w_prime, channel]
                        image[h_prime, w_prime, channel] = value
                    offset_index += 1


def fast_glass_blur(x: Any, severity: int = 1) -> np.ndarray:
    """Drop-in replacement for LIBERO-plus ``glass_blur``.

    The random offsets are generated by NumPy before entering the compiled
    kernel.  This preserves the upstream NumPy RNG stream and the exact
    sequence of offsets consumed by the nested Python loops.
    """

    if not NUMBA_AVAILABLE:  # pragma: no cover - guarded by patch helper
        raise RuntimeError("fast_glass_blur requires numba")

    # Keep this table synchronized with LIBERO-plus env_wrapper.py.
    sigma, max_delta, iterations = [
        (0.5, 1, 3),
        (0.7, 1, 3),
        (0.9, 2, 3),
        (1.0, 2, 2),
        (1.1, 3, 2),
        (1.3, 3, 2),
        (1.5, 4, 2),
        (1.8, 4, 2),
        (2.2, 5, 1),
        (2.5, 5, 1),
    ][severity - 1]

    image = np.uint8(gaussian(np.array(x) / 255.0, sigma=sigma, channel_axis=-1) * 255)
    height, width = image.shape[:2]
    swaps_per_iteration = (height - 2 * max_delta) * (width - 2 * max_delta)
    if swaps_per_iteration <= 0:
        raise ValueError(f"Image is too small for glass blur: shape={image.shape}, max_delta={max_delta}")

    # Generate all offsets in one NumPy call, in the same order as the
    # original repeated np.random.randint(..., size=(2,)) calls.
    offsets = np.random.randint(
        -max_delta,
        max_delta,
        size=(iterations * swaps_per_iteration, 2),
        dtype=np.int64,
    )
    _apply_pixel_swaps(image, offsets, max_delta, iterations)
    return np.clip(gaussian(image / 255.0, sigma=sigma, channel_axis=-1), 0, 1) * 255


def patch_libero_glass_blur() -> bool:
    """Install the accelerated transform in the vendored LIBERO module."""

    if not NUMBA_AVAILABLE:
        LOGGER.warning("numba is unavailable; using the original slow LIBERO-plus glass_blur")
        return False

    from libero.libero.envs import env_wrapper

    env_wrapper.glass_blur = fast_glass_blur
    LOGGER.info("Enabled compiled LIBERO-plus glass_blur sensor-noise transform")
    return True

